#include <iostream>
#include <fstream>
#include <string>

int main() {
    std::ifstream file("my_symlink_to_file.txt"); // This will be the symlink
    if (file.is_open()) {
        std::string line;
        while (getline(file, line)) {
            std::cout << line << std::endl;
        }
        file.close();
    } else {
        std::cerr << "Error: Unable to open my_symlink_to_file.txt" << std::endl;
        return 1;
    }
    return 0;
}

