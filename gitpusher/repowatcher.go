type RepoWatcher struct {
	config         *RepoConfig
	dirPath        string
	abfsClient     remote.RemoteProvider
	remoteName     string
	pushedRefsFile string
	shgit          *shellgit.ShellGit
	gitRepo        *git.Repository

	state            RepoWatcherState
	listStart        time.Time
	listDuration     time.Duration
	lastSuccess      time.Time
	lastErr          error
	lastManifestRead time.Time
}

type RepoWatcherState int

const (
	RepoWatcherCreated RepoWatcherState = iota
	RepoWatcherInitialized
	RepoWatcherSleep
	RepoWatcherFetch
	RepoWatcherManifestRead
)

func (s RepoWatcherState) String() string {
	switch s {
	case RepoWatcherCreated:
		return "created"
	case RepoWatcherInitialized:
		return "initialized"
	case RepoWatcherSleep:
		return "sleep"
	case RepoWatcherFetch:
		return "fetch"
	case RepoWatcherManifestRead:
		return "manifest-read"
	default:
		return fmt.Sprintf("unknown state: %d", s)
	}
}

func newRepoWatcher(config *RepoConfig, g *GitPusher) ProjectLister {
	dirPath := path.Join(g.projectStoragePath, "manifest", config.Manifest.Server, config.Manifest.Project+".git")

	return &RepoWatcher{
		config:         config,
		dirPath:        dirPath,
		remoteName:     defaultRemoteName,
		abfsClient:     g.limitedRemote,
		pushedRefsFile: path.Join(dirPath, pushedRefsFile),
		shgit:          g.shgit,
	}
}

// Stat implements ProjectLister.
func (m *RepoWatcher) Stat() RepoStat {
	lastErr := ""
	if m.lastErr != nil {
		lastErr = m.lastErr.Error()
	}
	return RepoStat{
		Name:          m.config.Name(),
		Remote:        m.config.Manifest.Server,
		URL:           m.config.Manifest.URL,
		State:         m.state.String(),
		FetchStart:    m.listStart.Format(time.RFC3339),
		FetchDuration: m.listDuration.Seconds(),
		LastSuccess:   m.lastSuccess.Format(time.RFC3339),
		LastError:     lastErr,
	}
}
func (m *RepoWatcher) writeGitConfig() error {
	var specs strings.Builder
	for _, branchFile := range m.config.Manifest.Files {
		fmt.Fprintf(&specs, "\tfetch = +refs/heads/%s:refs/remotes/%s/%s\n", branchFile.Branch, m.remoteName, branchFile.Branch)
	}

	template := `# Generated by GitPusher
[core]
	repositoryformatversion = 0
	filemode = true
	bare = true
[remote "%s"]
	url = %s
	tagOpt = --no-tags
%s
`
	config := fmt.Sprintf(template, m.remoteName, m.config.Manifest.URL, specs.String())

	return os.WriteFile(path.Join(m.dirPath, "config"), []byte(config), 0644)
}

func (m *RepoWatcher) init() error {
	r, err := getOrCreateGitRepo(m.dirPath)
	if err != nil {
		return err
	}
	m.gitRepo = r

	if err := m.writeGitConfig(); err != nil {
		return err
	}

	m.state = RepoWatcherInitialized
	return nil
}

// ListProjects implements ProjectLister.
func (m *RepoWatcher) ListProjects(ctx context.Context) (projects []*ProjectConfig, err error) {
	defer func() {
		m.lastErr = err
	}()

	if m.state == RepoWatcherCreated {
		if err := m.init(); err != nil {
			return nil, err
		}
	}

	m.listStart = time.Now()
	defer func() {
		m.listDuration = time.Since(m.listStart)
		m.state = RepoWatcherSleep
	}()

	m.state = RepoWatcherFetch
	if err := fetchWithRetry(m.shgit, m.dirPath); err != nil {
		return nil, err
	}

	// get a new repo object so it doesn't use cached data
	manifestRepo, err := getOrCreateGitRepo(m.dirPath)
	if err != nil {
		return nil, err
	}
	m.gitRepo = manifestRepo

	m.lastManifestRead = time.Now()

	// Parse the manifest in (name, remote, url) groupings.
	// We later drop the remote portion.
	allProjects, err := m.getUniqueProjectsForBranches()
	if err != nil {
		return nil, err
	}

	result := make([]*ProjectConfig, 0, len(allProjects)+1)
	addProject := func(project projectRemoteSchemeURL) error {
		fetchConfig := m.config.ProjectDefaults

		excluded := false

		for _, override := range m.config.Overrides {
			matches := false
			if override.Regex {
				if override.RegexPattern.MatchString(project.name) {
					matches = true
				}
			} else if override.Name == project.name {
				matches = true
			}
			if matches {
				if override.Exclude {
					excluded = true
				}
				fetchConfig.Override(&override.FetchConfig)
			}
		}
		if excluded {
			return nil
		}

		p := &ProjectConfig{
			Project:     project.name,
			Server:      project.server,
			URL:         instance.MaybeAddScheme(project.url, project.scheme),
			FetchConfig: fetchConfig,
		}
		if err := p.Validate(); err != nil {
			return err
		}
		result = append(result, p)
		return nil
	}

	for project := range allProjects {
		if err := addProject(project); err != nil {
			return nil, err
		}
	}

	manProject := projectRemoteSchemeURL{
		name:   m.config.Manifest.Project,
		server: m.config.Manifest.Server,
		url:    m.config.Manifest.URL,
	}
	if err := addProject(manProject); err != nil {
		return nil, err
	}

	m.lastSuccess = time.Now()
	return result, nil
}

func (m *RepoWatcher) getUniqueProjectsForBranches() (map[projectRemoteSchemeURL]struct{}, error) {
	uniqueProjectSet := make(map[projectRemoteSchemeURL]struct{})
	for _, manifestSpec := range m.config.Manifest.Files {
		// TODO: I'm confused why all of the origin/<branch> are missing except for one dev branch, but
		// the <branch> are present.
		branch := manifestSpec.Branch
		manifestFile := manifestSpec.File

		hash, err := m.gitRepo.ResolveRevision(plumbing.Revision(fmt.Sprintf("%s/%s", m.remoteName, branch)))
		if err != nil {
			return nil, fmt.Errorf("failed to resolve the revision for branch %q: %w", branch, err)
		}

		branchCommitObject, err := m.gitRepo.Object(plumbing.CommitObject, *hash)
		if err != nil {
			return nil, fmt.Errorf("failed to find commit object for hash %q: %w", *hash, err)
		}
		branchCommit, ok := branchCommitObject.(*object.Commit)
		if !ok {
			return nil, fmt.Errorf("git object loaded for hash %q was not a commit object", *hash)
		}

		contentor := &objectContentor{branchCommit}

		_, err = contentor.Contents(manifestFile)
		if err != nil {
			return nil, fmt.Errorf("failed to find manifest file %v on branch %v: %w", manifestFile, branch, err)
		}

		mappings, err := projectMappingsForFile(contentor, m.config.Manifest.URL, manifestFile)
		if err != nil {
			return nil, err
		}
		if err := mappings.updateProjectRemoteURLSet(uniqueProjectSet); err != nil {
			return nil, err
		}
	}

	return uniqueProjectSet, nil
}

// contentor is an interface to read the contents of a manifest file.
type contentor interface {
	Contents(string) (string, error)
}

// forAllManifests visits the manifest tree in a DFS pre-order fashion and executes the provided function.
func forAllManifests(contentor contentor, manifestFile string, onParse func(*manifest.Manifest) error) error {
	const notParsed = -1

	type stackEntry struct {
		manifestFile string
		includes     []*manifest.Include
		currInc      int
	}

	stack := []*stackEntry{
		{
			manifestFile: manifestFile,
			currInc:      notParsed,
		},
	}

	seen := make(map[string]bool)
	for len(stack) != 0 {
		// Peek at top of the stack.
		entry := stack[len(stack)-1]

		// Parse the node if we haven't yet.
		if entry.currInc == notParsed {
			contents, err := contentor.Contents(entry.manifestFile)
			if err != nil {
				return err
			}

			man, err := manifest.Parse([]byte(contents))
			if err != nil {
				return fmt.Errorf("failed to parse file %q as a manifest file: %w", entry.manifestFile, err)
			}

			if err := onParse(man); err != nil {
				return err
			}

			entry.includes = man.Include
			entry.currInc = 0
		}

		// Pop this entry from the stack if we're on the last child.
		if len(entry.includes) == 0 || entry.currInc == len(entry.includes)-1 {
			stack = stack[:len(stack)-1]
		}

		// Add next child.
		if entry.currInc < len(entry.includes) {
			inc := entry.includes[entry.currInc]
			entry.currInc++
			if seen[inc.Name] {
				continue
			}
			seen[inc.Name] = true

			stack = append(stack, &stackEntry{
				manifestFile: inc.Name,
				currInc:      notParsed,
			})
		}
	}

	return nil
}

// projectRemote pairs a project name with a remote name.
type projectRemote struct {
	// Name of the remote (not the resolved URL)
	// Empty string implies default
	remote string

	// Per repo docs: the URL will be the concatenation of {Remote URL, name.git}
	name string
}

// projectMappings contain project and remote mappings.
type projectMappings struct {
	// Name of the default Remote (not the resolved URL)
	defaultRemote string

	// Map the name of the remote to the resolved URL
	remotes map[string]string

	projectRemotes map[projectRemote]struct{}
}

// projectRemoteSchemeURL contains the necessary information needed to create a directory and fetch from a remote URL.
// We track scheme here because this is a manifest-layer data structure, and consumers need the scheme information to create remotes.
type projectRemoteSchemeURL struct {
	name   string
	server string
	remote string
	scheme string
	url    string
}

func (p *projectRemoteSchemeURL) String() string {
	return p.name + p.remote + p.scheme + p.url
}

// updateProjectRemoteURLSet updates the input set with new values from the state of ProjectMappings.
func (p *projectMappings) updateProjectRemoteURLSet(set map[projectRemoteSchemeURL]struct{}) error {
	for projectRemote := range p.projectRemotes {
		remote := projectRemote.remote
		if remote == "" {
			remote = p.defaultRemote
		}

		remoteSchemeURL := p.remotes[remote]
		resolvedSchemeURL, err := url.JoinPath(remoteSchemeURL, projectRemote.name)
		if err != nil {
			return err
		}
		u, err := url.Parse(resolvedSchemeURL)
		if err != nil {
			return err
		}

		pru := projectRemoteSchemeURL{
			name:   projectRemote.name,
			server: u.Host,
			remote: remote,
			scheme: u.Scheme,
			url:    instance.MaybeRemoveScheme(resolvedSchemeURL),
		}
		set[pru] = struct{}{}
	}

	return nil
}

// projectMappingsForFile returns project and remote mappings discovered from parsing a manifest tree.
func projectMappingsForFile(contentor contentor, manifestURL string, manifestFile string) (projectMappings, error) {
	remotes := make(map[string]string)
	projectRemotes := make(map[projectRemote]struct{})

	projectMappings := projectMappings{
		remotes:        remotes,
		projectRemotes: projectRemotes,
	}
	baseSchemeURL, err := url.Parse(manifestURL)
	if err != nil {
		return projectMappings, err
	}
	numDefaults := 0

	err = forAllManifests(contentor, manifestFile, func(m *manifest.Manifest) error {
		// Grab all the remotes.
		for _, remote := range m.Remote {
			fetchSchemeURL, err := url.Parse(remote.Fetch)
			if err != nil {
				return err
			}
			// This matches the Python urljoin behavior that the repo tool uses.
			resolvedSchemeURL := baseSchemeURL.ResolveReference(fetchSchemeURL)
			if curr, found := remotes[remote.Name]; found {
				if curr != resolvedSchemeURL.String() {
					return fmt.Errorf("duplicate remote found with different fetch url. Original: %q, Duplicate: %q", curr, resolvedSchemeURL)
				}
			} else {
				remotes[remote.Name] = resolvedSchemeURL.String()
			}
		}

		// Check for default.
		if m.Default != nil {
			numDefaults++
			if numDefaults > 1 {
				return errors.New("more than one default element found")
			}

			projectMappings.defaultRemote = m.Default.Remote
		}

		for _, project := range m.Project {
			projectRemotes[projectRemote{
				name:   project.Name,
				remote: project.Remote,
			}] = struct{}{}
		}

		return nil
	})

	return projectMappings, err
}

// objectContentor reads a manifestFile contents at a specific commit.
type objectContentor struct {
	commit *object.Commit
}

func (o *objectContentor) Contents(manifestFile string) (string, error) {
	if o.commit == nil {
		return "", errors.New("commit is nil")
	}
	file, err := o.commit.File(manifestFile)
	if err != nil {
		return "", fmt.Errorf("failed to find file %q at commit with hash %q: %w", manifestFile, o.commit.Hash, err)
	}

	return file.Contents()
}
