func (c *setupCmd) Exec(ctx context.Context, fl *pflag.FlagSet) error {
	var err error
	start := args.EnsureSingleArg(fl)
	c.mountPoint, err = cmd.MountPoint(start)
	if err != nil {
		log.Fatalf("Could not find mount point: %v", err)
	}

	// Ensure that Chroot isn't written into ninjago.conf
	// with trailing /
	if c.Chroot != "" {
		c.Chroot = filepath.Clean(c.Chroot)
	}

	nsjailCfg, err := entities.LoadNSJailConfig(c.mountPoint)
	if err != nil && !entities.IsNotExist(err) {
		fmt.Printf("Warning: failed to load nsjail config file: %v\n", err)
	}

	if c.AndroidTarget != "" {
		overlays := nsjailCfg.OverlaysForBuildTarget(c.AndroidTarget)
		views := nsjailCfg.ViewsForBuildTarget(c.AndroidTarget)

		fmt.Printf("Overlays for Android target %s: %s\n", c.AndroidTarget, overlays)
		fmt.Printf("Views for Android target %s: %s\n", c.AndroidTarget, views)

		if (len(overlays) + len(views)) > 0 {
			if c.Chroot == "" {
				return clierr.CLIErr("Chroot is necessary to apply overlays. Please use --chroot/-c option.")
			}
		}
	}

	if c.listOverlays {
		return c.printOverlays()
	}

	if c.Chroot != "" && len(c.Tops) > 0 {
		return clierr.CLIErr("--chroot and --top cannot be used together")
	}

	if c.BuildFromSource && c.CompiledDir != "" {
		return clierr.CLIErr("--source and --compiled cannot be used together")
	}

	if c.ConfigProvider == nil {
		return clierr.CLIErr("ConfigProvider of setup cmd not set")
	}

	if c.Config == nil {
		return clierr.CLIErr("Config of setup cmd not set")
	}

	if c.listTopsOnly {
		tops, source, err := c.findTops(start)
		if err != nil {
			return err
		}
		return c.listTops(os.Stdout, tops, source)
	}

	client, err := binding.NewClient(c.mountPoint, entities.ABFSSocketFileName, c.Config.CacheDir, c.Config.LocalOnly, c.Config.FetchTimeout)
	if err != nil {
		return err
	}
	defer func() {
		if err := client.Close(); err != nil {
			fmt.Printf("Error closing abfs client: %v\n", err)
		}
	}()
	c.abfs = client

	return c.run(start)
}

func (c *setupCmd) goBuild(args ...string) error {
	args = append([]string{"build"}, args...)
	cmd := exec.Command("go", args...)
	cmd.Dir = c.abfsSourceDir
	cmd.Env = os.Environ()
	if c.DisableCGO {
		cmd.Env = append(cmd.Env, "CGO_ENABLED=0")
	}
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	return cmd.Run()
}

// TODO: Remove this after prebuilts are checked in
func (c *setupCmd) createPrebuilts() error {
	c.log("Copying ABFS binaries...")

	if err := c.writeGitExclude(); err != nil {
		c.log("Failed to write git exclude file, so abfs binaries will appear in repo status. err: %v", err)
	}

	if err := c.installABFSWrap(); err != nil {
		return err
	}

	if err := c.installABFSBox(); err != nil {
		return err
	}

	if err := c.patchCKati(); err != nil {
		return err
	}

	if err := c.installNinja(); err != nil {
		return err
	}

	if err := c.installABFSMap(); err != nil {
		return err
	}

	if err := c.installABFSBazelDaemon(); err != nil {
		return err
	}

	if err := c.installRbetap(); err != nil {
		return err
	}

	return c.installTap()
}

func (c *setupCmd) run(start string) error {
	if c.BuildFromSource {
		if _, err := os.Stat("./cmd/abfs/abfs.go"); entities.IsNotExist(err) {
			return clierr.CLIErr("'setup' must be ran from abfs module root with --source")
		}
	}

	tops, source, err := c.findTops(start)
	if err != nil {
		return err
	}
	names := make([]string, len(tops))
	for i, top := range tops {
		names[i] = displayTop(top)
	}
	c.log("Set up the Soong tops in %s (%s): %s", c.mountPoint, source, strings.Join(names, " "))
	for _, top := range tops {
		if err := c.setupTop(top); err != nil {
			return fmt.Errorf("failed to set up %s: %w", filepath.Join(c.mountPoint, top), err)
		}
	}
	return nil
}

// setupTop installs the ABFS build hooks in one Soong top, given relative to the mount point.
// It runs on every mount, remount and sync, so it rewrites what an earlier run wrote.
func (c *setupCmd) setupTop(top string) error {
	c.top = top
	topDir := filepath.Join(c.mountPoint, top)
	if top != "" {
		if err := c.setupChroot(topDir); err != nil {
			return err
		}
	}

	c.buildToolsDir = filepath.Join(topDir, buildToolsRelativeDir)
	binDirPath, err := binDir()
	if err != nil {
		return err
	}
	c.abfsDir = filepath.Join(topDir, binDirPath)
	if err := os.MkdirAll(c.abfsDir, 0700); err != nil {
		return err
	}

	// Replacing a binary that a running build executes fails with ETXTBSY.
	if buildRunning(topDir) {
		c.warnf("Warning: a build is running in %s (%s exists without %s), so setup does not replace its ABFS binaries; run abfs setup again after the build, or delete %s if no build is running\n",
			topDir, buildStartFile(topDir), buildInfoFile(topDir), buildStartFile(topDir))
	} else if err := c.createPrebuilts(); err != nil {
		return err
	}

	if err := c.wrapNSJail(); err != nil {
		return err
	}

	if err := c.writeNinjaConfig(); err != nil {
		return err
	}

	// Not fatal: the build still works if the user exports the variables themselves.
	if err := c.writeVendorSetup(); err != nil {
		fmt.Fprintf(os.Stderr, "WARNING: %v\nSoong may not use ninjago; run `export SOONG_NINJA=ninjago` before building.\n", err)
	}

	if c.DoBlueprintPatch {
		if err := c.patchBlueprint(); err != nil {
			return err
		}
	}

	return nil
}

func (c *setupCmd) log(format string, a ...any) {
	if !c.quiet {
		fmt.Printf(format+"\n", a...)
	}
}

func (c *setupCmd) getEffectiveOverlays() []string {
	nsjailCfg, err := entities.LoadNSJailConfig(c.mountPoint)

	if err != nil {
		if !entities.IsNotExist(err) {
			fmt.Printf("Warning: failed to load nsjail config file: %v\n", err)
		}
		return nil
	}
	return nsjailCfg.OverlaysForBuildTarget(c.AndroidTarget)
}

func (c *setupCmd) getEffectiveViews() []string {
	nsjailCfg, err := entities.LoadNSJailConfig(c.mountPoint)
	if err != nil {
		return nil
	}
	return nsjailCfg.ViewsForBuildTarget(c.AndroidTarget)
}

func (c *setupCmd) printOverlays() error {
	fmt.Println("Available overlays from the source tree:")
	entries, err := os.ReadDir(filepath.Join(c.mountPoint, "overlays"))
	if err != nil {
		return err
	}

	for _, ent := range entries {
		if ent.IsDir() && !strings.HasPrefix(ent.Name(), ".") {
			fmt.Printf("  %s\n", ent.Name())
		}
	}
	return nil
}

// buildRunning reports whether a build is running in the top at dir: abfsbox writes
// .build_start when a build starts and .build_info when it ends.
func buildRunning(dir string) bool {
	if _, err := os.Stat(buildStartFile(dir)); err != nil {
		return false
	}
	_, err := os.Stat(buildInfoFile(dir))
	return entities.IsNotExist(err)
}

func buildStartFile(dir string) string {
	return filepath.Join(outDirOf(dir), ".build_start")
}

func buildInfoFile(dir string) string {
	return filepath.Join(outDirOf(dir), ".build_info")
}

func outDirOf(dir string) string {
	if filepath.IsAbs(entities.OutDir) {
		return entities.OutDir
	}
	return filepath.Join(dir, entities.OutDir)
}

// setupChroot gives a top below the mount root its own daemon socket and the mount details
// that soong_ui and abfsbox read there.
func (c *setupCmd) setupChroot(p string) error {
	if c.Chroot == "" {
		c.log("Create chroot for %s", c.top)
		if err := c.abfs.Chroot(c.top, nil, nil); err != nil {
			return err
		}
		if err := includeTop(p); err != nil {
			return err
		}
		// Setup used to copy the mount details into the top, and abfsbox prefers such a
		// copy over the link.
		if err := os.Remove(filepath.Join(p, abfs.MountDetailsFileName)); err != nil && !entities.IsNotExist(err) {
			return err
		}
		return linkMountDetails(p, c.top)
	}

	// A --chroot is a scratch checkout of its own, which abfs nsjail runs a build in with
	// nothing of the mount around it, so it keeps its own copy of the mount details.
	overlays, views := c.getEffectiveOverlays(), c.getEffectiveViews()
	c.log("Create chroot for %s, mount %s overlays on top, and exclude from parent hash. Including projects that that contain these views: %s",
		c.Chroot,
		strings.Join(overlays, ","),
		strings.Join(views, "\n"),
	)
	if err := c.abfs.Chroot(c.Chroot, overlays, views); err != nil {
		return err
	}

	// Exclude chroot from parent hash
	if err := bindcas.SetExcluded(p, true); err != nil {
		return err
	}

	// the mount-details object is needed inside the chroot for abfsbox build-started and build-finished
	sourceMountDetails := filepath.Join(c.mountPoint, abfs.MountDetailsFileName)
	destMountDetails := filepath.Join(c.mountPoint, c.Chroot, abfs.MountDetailsFileName)
	if err := os.MkdirAll(filepath.Dir(destMountDetails), 0755); err != nil {
		return fmt.Errorf("error while creating directory for mount details %s: %w", filepath.Dir(destMountDetails), err)
	}
	if err := os.WriteFile(destMountDetails, nil, 0644); err != nil {
		return fmt.Errorf("error while creating mount details file %s: %w", destMountDetails, err)
	}
	if err := bindcas.CopyHashSize(sourceMountDetails, destMountDetails); err != nil {
		return fmt.Errorf("error while reading copying mount details file hash/size from %s to %s: %w", sourceMountDetails, destMountDetails, err)
	}
	if err := bindcas.SetExcluded(destMountDetails, true); err != nil {
		return fmt.Errorf("error while setting mount details file %s as excluded: %w", destMountDetails, err)
	}

	// Soong expects the mount-details file to be at .repo/mount-details inside the chroot
	chrootRepoDir := filepath.Join(c.mountPoint, c.Chroot, ".repo")
	if err := os.MkdirAll(chrootRepoDir, 0755); err != nil {
		return fmt.Errorf("error creating .repo directory in chroot: %w", err)
	}
	chrootMountDetailsSym := filepath.Join(chrootRepoDir, "mount-details")
	// Relative symlink .repo/mount-details -> ../.abfs.mount-details; a top set up before
	// may have one that points out of the chroot.
	return replaceLink(chrootMountDetailsSym, filepath.Join("..", abfs.MountDetailsFileName))
}

// includeTop keeps a top in the workspace snapshot, so that the files a user keeps there
// survive a remount. Setup used to exclude the top, so this clears the flag on a tree set up
// before. A project directory stays excluded: the snapshot keeps it as a git repository.
func includeTop(dir string) error {
	excluded, err := bindcas.Excluded(dir)
	if err != nil || !excluded {
		return err
	}
	if _, err := os.Lstat(filepath.Join(dir, ".git")); err == nil {
		return nil
	}
	log.Printf("Include %s in the workspace snapshot again", dir)
	return bindcas.SetExcluded(dir, false)
}

// linkMountDetails points <top>/.repo/mount-details at the mount details in the mount root,
// with a relative link that also resolves in another mount of the same workspace.
func linkMountDetails(topDir, top string) error {
	target := strings.Repeat("../", strings.Count(filepath.ToSlash(top), "/")+2) + abfs.MountDetailsFileName
	repoDir := filepath.Join(topDir, casgit.RepoDirName)
	if err := os.MkdirAll(repoDir, 0755); err != nil {
		return fmt.Errorf("failed to create %s: %w", repoDir, err)
	}
	return replaceLink(filepath.Join(repoDir, "mount-details"), target)
}

// replaceLink makes link a symlink to target, replacing a symlink to anything else.
func replaceLink(link, target string) error {
	current, err := os.Readlink(link)
	switch {
	case err == nil && current == target:
		return nil
	case err == nil:
		if err := os.Remove(link); err != nil {
			return fmt.Errorf("failed to replace %s: %w", link, err)
		}
	case !entities.IsNotExist(err):
		return fmt.Errorf("failed to read %s: %w", link, err)
	}
	if err := os.Symlink(target, link); err != nil {
		return fmt.Errorf("failed to link %s to %s: %w", link, target, err)
	}
	return nil
}

func (c *setupCmd) installBinary(binary string, buildOpts []string) error {
	noCGoBinary := binary + "-no-cgo"

	destPath := filepath.Join(c.abfsDir, binary)
	if c.CompiledDir != "" {
		if c.DisableCGO {
			binaryPath := filepath.Join(c.CompiledDir, noCGoBinary)
			if c.verbose {
				c.log("Copy compiled %s command-line from %q to %q", noCGoBinary, binaryPath, destPath)
			}
			if err := copyFile(destPath, 0755, binaryPath); err == nil || !entities.IsNotExist(err) {
				return err
			}
			// if it wasn't found (err == isNotExist), fall though to check for regular binary
		}
		binaryPath := filepath.Join(c.CompiledDir, binary)
		if c.verbose {
			c.log("Copy compiled %s from %q to %q", binary, binaryPath, destPath)
		}
		return copyFile(destPath, 0755, binaryPath)
	} else if !c.BuildFromSource && c.DisableCGO {
		path := getExecutablePath(noCGoBinary)
		if path == "" {
			// Setup runs on every mount, so it never compiles here.
			return fmt.Errorf("cannot find %s on PATH (%s): install the client binaries with `make install-client` and put their directory on the PATH of the process that runs abfs mount, or pass --compiled or --source to abfs setup", noCGoBinary, os.Getenv("PATH"))
		}
		if c.verbose {
			c.log("Copy compiled %s command-line from %q to %q", noCGoBinary, path, destPath)
		}
		return copyFile(destPath, 0755, path)
	}
	if c.verbose {
		c.log("Compile %s and write it to %s", binary, destPath)
	}
	opts := append([]string{"-o", destPath}, buildOpts...)
	return c.goBuild(opts...)
}

// writeGitExclude is so that our binaries don't show up in `repo status` or `git status`
// in the prebuilts/build-tools project.
func (c *setupCmd) writeGitExclude() (returnErr error) {
	content := []byte(
		`# AUTO-GENERATED BY ABFS
# These are the binaries that abfs added here and we are hiding them from your repo status command
/*-x86/bin/abfs*
/*-x86/bin/ckati-wrap
/*-x86/bin/ninjago
/*-x86/bin/tap
/*-x86/bin/rbetap
# END AUTO-GENERATED BY ABFS
`)
	excludePath := filepath.Join(c.buildToolsDir, ".git", "info", "exclude")
	// skip writing if it already has our header in it
	if _, err := os.Stat(excludePath); err == nil {
		if existing, err := os.ReadFile(excludePath); err == nil {
			if strings.Contains(string(existing), "AUTO-GENERATED BY ABFS") {
				return nil
			}
		}
	}
	if err := os.MkdirAll(filepath.Dir(excludePath), 0755); err != nil {
		return fmt.Errorf("failed to create git excludes directory %q: %w", filepath.Dir(excludePath), err)
	}
	// append in case file already exists with some content
	f, err := os.OpenFile(excludePath, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		return fmt.Errorf("failed to open git excludes file %q: %w", excludePath, err)
	}
	defer func() {
		if err := f.Close(); err != nil && returnErr == nil {
			returnErr = fmt.Errorf("failed to close git excludes file %q: %w", excludePath, err)
		}
	}()
	if _, err := f.Write(content); err != nil {
		return fmt.Errorf("failed to append to git excludes file %q: %w", excludePath, err)
	}
	return nil
}

