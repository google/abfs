const buildToolsRelativeDir = "prebuilts/build-tools"

// build/envsetup.sh sources every vendorsetup.sh found under device/, vendor/
// and product/ (up to 4 levels deep), so this is picked up by the usual `source
// build/envsetup.sh` flow without patching any Android project.
const vendorSetupRelativePath = "vendor/abfs/vendorsetup.sh"

// vendorSetupContent mirrors maybeCoerceEnvForABFS() in newer
// platform/build/soong releases (cmd/soong_ui/main.go), which AOSP releases up
// to and including android17-release lack. Without it, soong_ui falls back to
// its default ninja implementation instead of ninjago, and user specific build
// metadata defeats cache hits between users. Releases that have the soong_ui
// coercion override these values themselves, so this file is harmless there.
//
// TODO: Remove this once AOSP releases are 26Q3 or later, which include the
// soong_ui coercion (BUILD_NUMBER=eng is only coerced starting in 26Q4).
const vendorSetupContent = `# AUTO-GENERATED BY ABFS. This file is rewritten by every "abfs setup ."
#
# Makes Soong builds in this ABFS workspace use ninjago and deterministic build
# metadata, mirroring maybeCoerceEnvForABFS() in newer build/soong releases.
# Values that are already set in the environment are kept.
#
# Set SKIP_ABFS_COERCE=1 before sourcing build/envsetup.sh to opt out.
if [ -z "${SKIP_ABFS_COERCE:-}" ]; then
    export SOONG_NINJA="${SOONG_NINJA:-ninjago}"            # Use ninjago for ABFS
    export BUILD_HOSTNAME="${BUILD_HOSTNAME:-abfs-builder}" # Static hostname for cache hits
    export BUILD_USERNAME="${BUILD_USERNAME:-abfs-builder}" # Static username for cache hits
    export BUILD_DATETIME="${BUILD_DATETIME:-1}"            # Static datetime for cache hits
    export BUILD_NUMBER="${BUILD_NUMBER:-eng}"              # Static build number for cache hits
fi
`

func binDir() (string, error) {
	switch runtime.GOOS {
	case "linux":
		return filepath.Join(buildToolsRelativeDir, "linux-x86", "bin"), nil
	case "darwin":
		return filepath.Join(buildToolsRelativeDir, "darwin-x86", "bin"), nil
	default:
		return "", fmt.Errorf("unsupported OS: %s", runtime.GOOS)
	}
}

