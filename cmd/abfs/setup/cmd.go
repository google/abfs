func (c *setupCmd) writeVendorSetup() error {
	root := filepath.Join(c.mountPoint, c.top)
	p := filepath.Join(root, vendorSetupRelativePath)
	c.log("Write %s", p)

	// Exclude the top-most directory that we create (e.g. vendor/ on AOSP,
	// which has no vendor projects), or just the file if the directories
	// already exist.
	excludePath := p
	if dir := topmostMissingDir(root, filepath.Dir(vendorSetupRelativePath)); dir != "" {
		excludePath = filepath.Join(root, dir)
	}

	if err := os.MkdirAll(filepath.Dir(p), 0755); err != nil {
		return fmt.Errorf("failed to create directory for %s: %w", p, err)
	}
	if err := os.WriteFile(p, []byte(vendorSetupContent), 0644); err != nil {
		return fmt.Errorf("failed to write %s: %w", p, err)
	}
	if err := bindcas.SetExcluded(excludePath, true); err != nil {
		return fmt.Errorf("failed to exclude %s from the tree hash: %w", excludePath, err)
	}
	return nil
}

// topmostMissingDir returns the shallowest directory in relDir (a path relative
// to root) that doesn't exist yet, or "" if all of them exist.
func topmostMissingDir(root, relDir string) string {
	missing := ""
	for d := filepath.Clean(relDir); d != "." && d != string(filepath.Separator); d = filepath.Dir(d) {
		if _, err := os.Lstat(filepath.Join(root, d)); errors.Is(err, os.ErrNotExist) {
			missing = d
		}
	}
	return missing
}

